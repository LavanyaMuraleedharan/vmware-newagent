class UnifiedContextBuilder:

    def __init__(self):

        self.documents: List[Dict[str, Any]] = []
        self.document_counter = 0

        KNOWLEDGE_DIR.mkdir(parents=True, exist_ok=True)

    # --------------------------------------------------------
    # COMMON DOCUMENT CREATION
    # --------------------------------------------------------

    def add_document(
        self,
        category: str,
        title: str,
        content: str,
        source: str,
        metadata: Optional[Dict[str, Any]] = None
    ):

        self.document_counter += 1

        document = {
            "id": f"doc_{self.document_counter:06d}",
            "category": category,
            "title": title,
            "content": content,
            "source": source,
            "metadata": metadata or {},
            "created_at": datetime.now().isoformat()
        }

        self.documents.append(document)

    # --------------------------------------------------------
    # FILE READING
    # --------------------------------------------------------

    @staticmethod
    def read_json(file_path: Path):

        if not file_path.exists():

            logger.warning(
                "File not found: %s",
                file_path
            )

            return None

        try:

            with open(
                file_path,
                "r",
                encoding="utf-8"
            ) as file:

                return json.load(file)

        except Exception as error:

            logger.error(
                "Could not read JSON %s: %s",
                file_path.name,
                error
            )

            return None

    @staticmethod
    def read_csv(file_path: Path):

        if not file_path.exists():

            logger.warning(
                "File not found: %s",
                file_path
            )

            return []

        try:

            with open(
                file_path,
                "r",
                encoding="utf-8-sig",
                newline=""
            ) as file:

                reader = csv.DictReader(file)

                return list(reader)

        except Exception as error:

            logger.error(
                "Could not read CSV %s: %s",
                file_path.name,
                error
            )

            return []

    @staticmethod
    def read_jsonl(file_path: Path):

        if not file_path.exists():

            logger.warning(
                "File not found: %s",
                file_path
            )

            return []

        documents = []

        try:

            with open(
                file_path,
                "r",
                encoding="utf-8"
            ) as file:

                for line_number, line in enumerate(
                    file,
                    start=1
                ):

                    if not line.strip():
                        continue

                    try:

                        documents.append(
                            json.loads(line)
                        )

                    except json.JSONDecodeError:

                        logger.warning(
                            "Invalid JSONL record in %s at line %s",
                            file_path.name,
                            line_number
                        )

        except Exception as error:

            logger.error(
                "Could not read JSONL %s: %s",
                file_path.name,
                error
            )

        return documents

    @staticmethod
    def value_to_text(value: Any) -> str:

        if value is None:
            return "Not available"

        if isinstance(value, (datetime, date)):
            return value.isoformat()

        if isinstance(value, (dict, list)):

            return json.dumps(
                value,
                ensure_ascii=False,
                default=str
            )

        return str(value)

    def relative_source(self, file_path: Path) -> str:

        try:

            return str(
                file_path.relative_to(PROJECT_ROOT)
            )

        except ValueError:

            return str(file_path)

    def add_csv_record_documents(
        self,
        file_path: Path,
        category: str,
        description: str,
        data_origin: str,
        max_records: Optional[int] = None
    ):

        """Create one knowledge document per CSV row."""

        rows = self.read_csv(file_path)

        if not rows:
            return 0

        selected_rows = (
            rows
            if max_records is None
            else rows[:max_records]
        )

        for index, row in enumerate(
            selected_rows,
            start=1
        ):

            content = (
                f"{description}\n"
                f"Source file: {file_path.name}\n"
                f"Record number: {index}\n"
                f"Data origin: {data_origin}\n"
            )

            for key, value in row.items():

                content += (
                    f"{key}: {self.value_to_text(value)}\n"
                )

            self.add_document(
                category=category,
                title=f"{file_path.stem} Record {index}",
                content=content,
                source=self.relative_source(file_path),
                metadata={
                    "data_origin": data_origin,
                    "dataset": file_path.name,
                    "record_number": index
                }
            )

        if (
            max_records is not None
            and len(rows) > max_records
        ):

            logger.info(
                "%s: indexed %s of %s rows",
                file_path.name,
                max_records,
                len(rows)
            )

        return len(selected_rows)

    # --------------------------------------------------------
    # 1. DATASET CATALOG KNOWLEDGE
    # --------------------------------------------------------

    def build_catalog_knowledge(self):

        catalog = self.read_json(CATALOG_FILE)

        if catalog is None:

            logger.warning(
                "Dataset catalog is unavailable."
            )

            return

        if isinstance(catalog, dict):

            datasets = catalog.get(
                "datasets",
                catalog.get("files", [])
            )

            if not isinstance(datasets, list):
                datasets = []

        elif isinstance(catalog, list):

            datasets = catalog

        else:

            datasets = []

        logger.info(
            "Catalog knowledge: %s datasets",
            len(datasets)
        )

        for index, dataset in enumerate(
            datasets,
            start=1
        ):

            if not isinstance(dataset, dict):
                continue

            title = (
                dataset.get("file_name")
                or dataset.get("filename")
                or dataset.get("name")
                or dataset.get("path")
                or f"Dataset {index}"
            )

            content = (
                "Infrastructure dataset information\n"
                f"Dataset name: {title}\n"
            )

            for key, value in dataset.items():

                content += (
                    f"{key}: {self.value_to_text(value)}\n"
                )

            category = (
                dataset.get("category")
                or dataset.get("domain")
                or "dataset_catalog"
            )

            self.add_document(
                category="dataset_catalog",
                title=str(title),
                content=content,
                source="dataset_catalog.json",
                metadata={
                    "dataset_category": str(category),
                    "data_origin": "catalog"
                }
            )

    # --------------------------------------------------------
    # 2. STORAGE KNOWLEDGE
    # --------------------------------------------------------

    def build_storage_knowledge(self):

        total_documents = 0

        for file_path in STORAGE_FILES:

            count = self.add_csv_record_documents(
                file_path=file_path,
                category="storage",
                description="Storage analytics information",
                data_origin="processed_dataset"
            )

            total_documents += count

        logger.info(
            "Storage knowledge: %s documents",
            total_documents
        )

    # --------------------------------------------------------
    # 3. DATABASE KNOWLEDGE
    # --------------------------------------------------------

    def build_database_knowledge(self):

        for file_path in DATABASE_FILES:

            rows = self.read_csv(file_path)

            if not rows:
                continue

            column_names = list(
                rows[0].keys()
            )

            content = (
                "Database performance dataset\n"
                f"Dataset name: {file_path.name}\n"
                f"Total records: {len(rows)}\n"
                f"Columns: {', '.join(column_names)}\n"
                "This dataset contains database-related "
                "performance measurements. It does not by itself "
                "provide confirmed infrastructure costs or savings.\n"
            )

            self.add_document(
                category="database",
                title=f"{file_path.stem} Dataset Overview",
                content=content,
                source=self.relative_source(file_path),
                metadata={
                    "record_count": len(rows),
                    "columns": column_names,
                    "data_origin": "reference_dataset"
                }
            )

            logger.info(
                "Database knowledge: %s",
                file_path.name
            )

    # --------------------------------------------------------
    # 4. BACKUP KNOWLEDGE
    # --------------------------------------------------------

    def build_backup_knowledge(self):

        total_records = 0

        for file_path in BACKUP_FILES:

            rows = self.read_csv(file_path)

            if not rows:
                continue

            file_title = (
                file_path.stem
                .replace("_", " ")
                .title()
            )

            columns = list(
                rows[0].keys()
            )

            profile_content = (
                f"Backup dataset: {file_title}\n"
                f"Source file: {file_path.name}\n"
                f"Total records: {len(rows)}\n"
                f"Available columns: {', '.join(columns)}\n"
                "Data origin: simulated\n"
                "This dataset is simulated project data and does not "
                "represent actual enterprise backup infrastructure records.\n"
            )

            self.add_document(
                category="backup",
                title=f"{file_title} Overview",
                content=profile_content,
                source=self.relative_source(file_path),
                metadata={
                    "record_count": len(rows),
                    "columns": columns,
                    "data_origin": "simulated"
                }
            )

            count = self.add_csv_record_documents(
                file_path=file_path,
                category="backup",
                description=(
                    f"Backup infrastructure record: {file_title}"
                ),
                data_origin="simulated"
            )

            total_records += count

            logger.info(
                "Backup %s: %s records processed",
                file_title,
                len(rows)
            )

        logger.info(
            "Total backup records processed: %s",
            total_records
        )

