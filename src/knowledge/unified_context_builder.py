    # --------------------------------------------------------
    # 6. COMPUTE/GPU KNOWLEDGE
    # --------------------------------------------------------

    def build_compute_gpu_knowledge(self):

        total_documents = 0

        # Overall ingestion summary.

        summary = self.read_json(
            COMPUTE_GPU_SUMMARY_FILE
        )

        if summary:

            content = (
                "Compute and GPU inventory summary\n"
                "The available records describe server and accelerator "
                "inventory/capacity. They do not provide CPU or GPU "
                "utilization measurements or confirmed cost data.\n"
            )

            for key, value in summary.items():

                content += (
                    f"{key}: {self.value_to_text(value)}\n"
                )

            self.add_document(
                category="compute_gpu",
                title="Compute GPU Inventory Summary",
                content=content,
                source=self.relative_source(
                    COMPUTE_GPU_SUMMARY_FILE
                ),
                metadata={
                    "data_origin": "reference_dataset",
                    "document_type": "inventory_summary"
                }
            )

            total_documents += 1

        # File-level ingestion metrics, if available.

        total_documents += self.add_csv_record_documents(
            file_path=COMPUTE_GPU_FILE_METRICS_FILE,
            category="compute_gpu",
            description=(
                "Compute/GPU source-file inventory metrics. "
                "These records describe inventory and capacity, "
                "not utilization or financial cost."
            ),
            data_origin="reference_dataset"
        )

        # Profile the server inventory without creating 29,000+
        # individual vector documents.

        server_rows = self.read_csv(
            COMPUTE_GPU_SERVER_FILE
        )

        if server_rows:

            gpu_models = Counter()
            clusters = set()
            server_count = len(server_rows)
            gpu_count_total = 0
            cpu_capacity_values = []

            for row in server_rows:

                specifications = (
                    row.get("gpu_specifications")
                    or row.get("gpu_spec_public")
                    or ""
                )

                if specifications:

                    for model in str(
                        specifications
                    ).split(","):

                        model = model.strip()

                        if model:
                            gpu_models[model] += 1

                cluster_value = row.get(
                    "cluster_ids",
                    ""
                )

                if cluster_value:

                    for cluster in str(
                        cluster_value
                    ).split(","):

                        cluster = cluster.strip()

                        if cluster:
                            clusters.add(cluster)

                try:

                    gpu_count_total += float(
                        row.get(
                            "gpu_count_max_observed"
                        ) or 0
                    )

                except (TypeError, ValueError):
                    pass

                try:

                    cpu_capacity_values.append(
                        float(
                            row.get(
                                "cpu_capacity_cores_max_observed"
                            ) or 0
                        )
                    )

                except (TypeError, ValueError):
                    pass

            profile_content = (
                "Compute/GPU server inventory profile\n"
                f"Unique server records: {server_count}\n"
                f"Unique clusters observed: {len(clusters)}\n"
                f"GPU model frequency: "
                f"{self.value_to_text(dict(gpu_models.most_common()))}\n"
                f"Sum of per-server maximum observed GPU counts: "
                f"{gpu_count_total}\n"
                f"Maximum CPU capacity observed per server: "
                f"{max(cpu_capacity_values) if cpu_capacity_values else 'Not available'}\n"
                "Important limitation: inventory and capacity fields "
                "cannot establish actual utilization, idle capacity, "
                "or financial savings. GPU and CPU telemetry is needed "
                "before utilization-based optimization.\n"
            )

            self.add_document(
                category="compute_gpu",
                title="Compute GPU Server Inventory Profile",
                content=profile_content,
                source=self.relative_source(
                    COMPUTE_GPU_SERVER_FILE
                ),
                metadata={
                    "data_origin": "reference_dataset",
                    "document_type": "inventory_profile",
                    "server_count": server_count,
                    "cluster_count": len(clusters)
                }
            )

            total_documents += 1

        logger.info(
            "Compute/GPU knowledge: %s documents",
            total_documents
        )

