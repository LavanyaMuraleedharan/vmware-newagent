    # --------------------------------------------------------
    # 8. DOMAIN-LEVEL KNOWLEDGE
    # --------------------------------------------------------

    def build_domain_knowledge(self):

        catalog = self.read_json(
            CATALOG_FILE
        )

        if not catalog:

            logger.warning(
                "Domain overview: catalog unavailable; "
                "creating overviews with zero registered catalog files."
            )

            datasets = []

        elif isinstance(catalog, dict):

            datasets = catalog.get(
                "datasets",
                catalog.get("files", [])
            )

            if not isinstance(datasets, list):
                datasets = []

        elif isinstance(catalog, list):

            datasets = []

        else:

            datasets = []

        category_counts = {}

        for dataset in datasets:

            if not isinstance(dataset, dict):
                continue

            category = (
                dataset.get("category")
                or dataset.get("domain")
                or "unknown"
            )

            category = str(category).lower()

            category_counts[category] = (
                category_counts.get(category, 0) + 1
            )

        project_domains = [
            "vmware",
            "storage",
            "backup",
            "compute_gpu",
            "database",
            "licensing"
        ]

        domain_limitations = {

            "vmware": (
                "Historical utilization measurements are not live "
                "enterprise telemetry. Low-utilization findings require "
                "workload and service validation."
            ),

            "storage": (
                "Performance measurements alone do not establish "
                "enterprise capacity utilization or actual storage costs."
            ),

            "backup": (
                "Backup operational and cost records are simulated "
                "project data, not actual enterprise records."
            ),

            "compute_gpu": (
                "Available records describe server/GPU inventory and "
                "capacity, not CPU/GPU utilization or actual costs."
            ),

            "database": (
                "Query and system profiling measurements do not by "
                "themselves establish database infrastructure costs."
            ),

            "licensing": (
                "License activity and cost records are simulated project "
                "data. Financial estimates are illustrative and require "
                "contract and business validation."
            )
        }

        for category in project_domains:

            count = category_counts.get(
                category,
                0
            )

            if category == "backup":

                data_origin = "simulated"

            elif category == "licensing":

                data_origin = "simulated"

            elif category in [
                "vmware",
                "compute_gpu",
                "database"
            ]:

                data_origin = "reference_dataset"

            else:

                data_origin = "processed_dataset"

            content = (
                f"Infrastructure domain: {category}\n"
                f"Registered datasets: {count}\n"
                f"Data origin: {data_origin}\n"
                f"Data limitations: "
                f"{domain_limitations.get(category, 'See source records.')}\n"
                "Use the domain's detailed analytics and source records "
                "when available. Do not infer actual costs or savings "
                "without a validated cost model.\n"
            )

            self.add_document(
                category=category,
                title=f"{category} Domain Overview",
                content=content,
                source="dataset_catalog.json",
                metadata={
                    "dataset_count": count,
                    "data_origin": data_origin,
                    "document_type": "domain_overview"
                }
            )

        logger.info(
            "Domain knowledge created."
        )

    # --------------------------------------------------------
    # 9. SAVE KNOWLEDGE BASE
    # --------------------------------------------------------

    def save_knowledge_base(self):

        knowledge_base = {

            "project": "Infrastructure FinOps",

            "description": (
                "Unified knowledge base for infrastructure FinOps "
                "analysis across VMware, Storage, Backup, Compute/GPU, "
                "Database and Licensing."
            ),

            "total_documents": len(self.documents),

            "generated_at": datetime.now().isoformat(),

            "documents": self.documents
        }

        with open(
            KNOWLEDGE_BASE_FILE,
            "w",
            encoding="utf-8"
        ) as file:

            json.dump(
                knowledge_base,
                file,
                indent=4,
                ensure_ascii=False,
                default=str
            )

        logger.info(
            "JSON saved: %s",
            KNOWLEDGE_BASE_FILE
        )

        with open(
            KNOWLEDGE_JSONL_FILE,
            "w",
            encoding="utf-8"
        ) as file:

            for document in self.documents:

                file.write(
                    json.dumps(
                        document,
                        ensure_ascii=False,
                        default=str
                    ) + "\n"
                )

        logger.info(
            "JSONL saved: %s",
            KNOWLEDGE_JSONL_FILE
        )

