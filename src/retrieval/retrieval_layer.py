
import argparse
import json
import logging
from pathlib import Path
from collections import Counter
from typing import Optional

import chromadb
from sentence_transformers import SentenceTransformer


# ============================================================
# 1. PATHS AND CONFIGURATION
# ============================================================

PROJECT_ROOT = Path(__file__).resolve().parents[2]

KNOWLEDGE_FILE = (
    PROJECT_ROOT
    / "data"
    / "processed"
    / "knowledge"
    / "knowledge_documents.jsonl"
)

CHROMA_PATH = (
    PROJECT_ROOT
    / "data"
    / "processed"
    / "chroma_db"
)

COLLECTION_NAME = "infrastructure_finops_knowledge"

EMBEDDING_MODEL = "all-MiniLM-L6-v2"

BATCH_SIZE = 100


# ============================================================
# 2. LOGGING
# ============================================================

logging.basicConfig(
    level=logging.INFO,
    format="[%(levelname)s] %(message)s"
)

logger = logging.getLogger(__name__)


# ============================================================
# 3. RETRIEVAL LAYER
# ============================================================

class RetrievalLayer:

    def __init__(self):

        print("[INFO] Loading embedding model...")

        self.embedding_model = SentenceTransformer(
            EMBEDDING_MODEL
        )

        print("[INFO] Connecting to ChromaDB...")

        CHROMA_PATH.mkdir(
            parents=True,
            exist_ok=True
        )

        self.client = chromadb.PersistentClient(
            path=str(CHROMA_PATH)
        )

        self.collection = self.client.get_or_create_collection(
            name=COLLECTION_NAME,
            metadata={
                "hnsw:space": "cosine"
            }
        )

        print("[SUCCESS] Retrieval layer initialized")

    # --------------------------------------------------------
    # 4. LOAD KNOWLEDGE DOCUMENTS
    # --------------------------------------------------------

    def load_documents(self):

        if not KNOWLEDGE_FILE.exists():

            raise FileNotFoundError(
                f"Knowledge file not found: {KNOWLEDGE_FILE}"
            )

        documents = []
        ids = []
        metadatas = []

        seen_ids = set()
        skipped_records = 0

        with open(
            KNOWLEDGE_FILE,
            "r",
            encoding="utf-8"
        ) as file:

            for line_number, line in enumerate(
                file,
                start=1
            ):

                if not line.strip():
                    continue

                try:

                    item = json.loads(line)

                except json.JSONDecodeError:

                    logger.warning(
                        "Invalid JSON at line %s",
                        line_number
                    )

                    skipped_records += 1
                    continue

                content = str(
                    item.get("content", "")
                ).strip()

                if not content:

                    skipped_records += 1
                    continue

                # Use the ID generated by unified_context_builder.py.
                document_id = str(
                    item.get("id")
                    or item.get("document_id")
                    or f"document-{line_number}"
                )

                # Prevent duplicate IDs in the input file.
                if document_id in seen_ids:

                    logger.warning(
                        "Duplicate document ID skipped: %s",
                        document_id
                    )

                    skipped_records += 1
                    continue

                seen_ids.add(document_id)

                category = str(
                    item.get("category", "general")
                )

                title = str(
                    item.get("title", "Untitled")
                )

                source = str(
                    item.get("source", "unknown")
                )

                metadata = {
                    "category": category,
                    "title": title,
                    "source": source
                }

                # Add extra metadata.
                additional_metadata = (
                    item.get("metadata") or {}
                )

                for key, value in additional_metadata.items():

                    if isinstance(
                        value,
                        (str, int, float, bool)
                    ):

                        metadata[str(key)] = value

                    elif value is not None:

                        metadata[str(key)] = json.dumps(
                            value,
                            ensure_ascii=False,
                            default=str
                        )

                documents.append(content)

                ids.append(document_id)

                metadatas.append(metadata)

        logger.info(
            "Documents loaded: %s",
            len(documents)
        )

        logger.info(
            "Skipped records: %s",
            skipped_records
        )

        return documents, ids, metadatas

    # --------------------------------------------------------
    # 5. INDEX DOCUMENTS INTO CHROMADB
    # --------------------------------------------------------

    def build_index(self, rebuild=False):

        documents, ids, metadatas = self.load_documents()

        if not documents:

            logger.warning(
                "No valid knowledge documents found."
            )

            return

        # Recreate collection when explicitly requested.
        if rebuild:

            print("[INFO] Rebuilding ChromaDB collection...")

            try:

                self.client.delete_collection(
                    name=COLLECTION_NAME
                )

            except Exception as error:

                logger.warning(
                    "Could not delete existing collection: %s",
                    error
                )

            self.collection = self.client.create_collection(
                name=COLLECTION_NAME,
                metadata={
                    "hnsw:space": "cosine"
                }
            )

        else:

            existing_count = self.collection.count()

            if existing_count > 0:

                print(
                    "[WARNING] ChromaDB already contains "
                    f"{existing_count} documents."
                )

                print(
                    "Use --rebuild to recreate the index."
                )

                return

        total = len(documents)

        print(
            f"\n[INFO] Documents to index: {total}"
        )

        category_counts = Counter(
            metadata["category"]
            for metadata in metadatas
        )

        print("\n[INFO] Documents by category:")

        for category, count in sorted(
            category_counts.items()
        ):

            print(
                f"  {category}: {count}"
            )

        # Index documents in batches.
        for start in range(
            0,
            total,
            BATCH_SIZE
        ):

            end = min(
                start + BATCH_SIZE,
                total
            )

            batch_documents = documents[start:end]

            batch_ids = ids[start:end]

            batch_metadata = metadatas[start:end]

            embeddings = self.embedding_model.encode(
                batch_documents,
                normalize_embeddings=True,
                show_progress_bar=False
            ).tolist()

            # Upsert safely handles existing document IDs.
            self.collection.upsert(
                ids=batch_ids,
                documents=batch_documents,
                metadatas=batch_metadata,
                embeddings=embeddings
            )

            print(
                f"[INFO] Indexed {end}/{total}"
            )

        print("\n" + "=" * 60)
        print("[SUCCESS] ChromaDB indexing completed")
        print("=" * 60)

        print(
            f"[INFO] Indexed documents: "
            f"{self.collection.count()}"
        )

        print(
            f"[INFO] Database location: {CHROMA_PATH}"
        )

    # --------------------------------------------------------
    # 6. RETRIEVE RELEVANT DOCUMENTS
    # --------------------------------------------------------

    def retrieve(
        self,
        query,
        top_k=5,
        category: Optional[str] = None
    ):

        if not query or not query.strip():

            raise ValueError(
                "Query cannot be empty."
            )

        if top_k < 1:

            raise ValueError(
                "top_k must be greater than zero."
            )

        # Apply category filter.
        filters = (
            {"category": category}
            if category
            else None
        )

        # ChromaDB count() does not support a where argument
        # in the installed version. Use get() to count matches.
        if filters:

            matching_documents = self.collection.get(
                where=filters,
                include=["metadatas"]
            )

            available_count = len(
                matching_documents.get("ids", [])
            )

        else:

            available_count = self.collection.count()

        if available_count == 0:

            print(
                "[WARNING] No matching documents found."
            )

            return []

        # Generate query embedding.
        query_embedding = self.embedding_model.encode(
            [query],
            normalize_embeddings=True
        ).tolist()

        # Search ChromaDB.
        results = self.collection.query(
            query_embeddings=query_embedding,
            n_results=min(
                top_k,
                available_count
            ),
            where=filters,
            include=[
                "documents",
                "metadatas",
                "distances"
            ]
        )

        retrieved_documents = []

        result_documents = (
            results.get("documents") or [[]]
        )

        result_metadatas = (
            results.get("metadatas") or [[]]
        )

        result_distances = (
            results.get("distances") or [[]]
        )

        for index, document in enumerate(
            result_documents[0]
        ):

            metadata = result_metadatas[0][index]

            distance = result_distances[0][index]

            retrieved_documents.append({

                "rank": index + 1,

                "document": document,

                "metadata": metadata,

                "distance": distance,

                "similarity": round(
                    1 - distance,
                    4
                )
            })

        return retrieved_documents

    # --------------------------------------------------------
    # 7. COLLECTION INFORMATION
    # --------------------------------------------------------

    def collection_info(self):

        total = self.collection.count()

        print("\n" + "=" * 60)
        print("CHROMADB COLLECTION INFORMATION")
        print("=" * 60)

        print(
            f"Collection name: {COLLECTION_NAME}"
        )

        print(
            f"Total indexed documents: {total}"
        )

        categories = [
            "vmware",
            "storage",
            "backup",
            "compute_gpu",
            "database",
            "licensing"
        ]

        print("\nDomain document counts:")

        for category in categories:

            # Use get() instead of count(where=...).
            result = self.collection.get(
                where={
                    "category": category
                },
                include=["metadatas"]
            )

            count = len(
                result.get("ids", [])
            )

            print(
                f"{category}: {count}"
            )

        # Dataset catalog count.
        catalog_result = self.collection.get(
            where={
                "category": "dataset_catalog"
            },
            include=["metadatas"]
        )

        print(
            "dataset_catalog: "
            f"{len(catalog_result.get('ids', []))}"
        )

        print("=" * 60)

    # --------------------------------------------------------
    # 8. TEST RETRIEVAL
    # --------------------------------------------------------

    def test_retrieval(
        self,
        query,
        category=None,
        top_k=5
    ):

        results = self.retrieve(
            query=query,
            top_k=top_k,
            category=category
        )

        print("\n" + "=" * 60)
        print("RETRIEVAL TEST")
        print("=" * 60)

        print(
            f"Query: {query}"
        )

        print(
            f"Category: {category or 'All domains'}"
        )

        print(
            f"Results found: {len(results)}"
        )

        for result in results:

            print("\n" + "-" * 60)

            print(
                f"Rank: {result['rank']}"
            )

            print(
                f"Similarity: {result['similarity']}"
            )

            print(
                f"Category: "
                f"{result['metadata'].get('category')}"
            )

            print(
                f"Title: "
                f"{result['metadata'].get('title')}"
            )

            print(
                f"Source: "
                f"{result['metadata'].get('source')}"
            )

            print(
                f"\n{result['document'][:1200]}"
            )

        print("\n" + "=" * 60)

        return results


# ============================================================
# 9. MAIN
# ============================================================

def main():

    parser = argparse.ArgumentParser(
        description="Infrastructure FinOps Retrieval Layer"
    )

    parser.add_argument(
        "--rebuild",
        action="store_true",
        help="Delete and recreate the ChromaDB collection."
    )

    parser.add_argument(
        "--query",
        type=str,
        help="Search the knowledge base."
    )

    parser.add_argument(
        "--top-k",
        type=int,
        default=5
    )

    parser.add_argument(
        "--category",
        type=str,
        help="Filter by domain category."
    )

    parser.add_argument(
        "--info",
        action="store_true",
        help="Display ChromaDB collection information."
    )

    args = parser.parse_args()

    retrieval = RetrievalLayer()

    if args.query:

        retrieval.test_retrieval(
            query=args.query,
            category=args.category,
            top_k=args.top_k
        )

    elif args.info:

        retrieval.collection_info()

    else:

        retrieval.build_index(
            rebuild=args.rebuild
        )


if __name__ == "__main__":

    main()
